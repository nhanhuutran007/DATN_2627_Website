const GROUP_PREFIXES: Array<[AuditGroup, string[]]> = [
  ["auth", ["auth."]],
  ["account", ["user."]],
  ["finance", ["donation.", "refund.", "finance."]],
  ["content", ["campaign.", "category.", "comment.", "milestone", "reward_tier.", "report.", "media.", "risk_alert."]],
  ["system", ["backup.", "admin."]],
];

export function auditGroup(action: string): AuditGroup | null {
  return GROUP_PREFIXES.find(([, prefixes]) => prefixes.some((prefix) => action.startsWith(prefix)))?.[0] ?? null;
}

